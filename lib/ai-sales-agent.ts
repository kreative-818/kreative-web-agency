export interface ConversationMessage {
  role: 'user' | 'assistant' | 'system';
  content: string;
}

export interface AgentDecision {
  action: 'CONTINUE' | 'CLOSE_DEAL' | 'TRANSFER_TO_HUMAN';
  thought: string;
  message: string;
  closeDetails?: {
    service: string;
    price: string;
    description: string;
  };
  transferDetails?: {
    reason: string;
    summary: string;
  };
}

export function parseAgentResponse(response: string): AgentDecision {
  const lines = response.split('\n');
  let thought = '';
  let action: 'CONTINUE' | 'CLOSE_DEAL' | 'TRANSFER_TO_HUMAN' = 'CONTINUE';
  let message = '';
  let service = '';
  let price = '';
  let description = '';
  let reason = '';
  let summary = '';

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    
    if (line.startsWith('THOUGHT:')) {
      thought = line.substring(8).trim();
    } else if (line.startsWith('ACTION:')) {
      const actionText = line.substring(7).trim();
      if (actionText === 'CLOSE_DEAL' || actionText === 'TRANSFER_TO_HUMAN' || actionText === 'CONTINUE') {
        action = actionText;
      }
    } else if (line.startsWith('MESSAGE:')) {
      message = line.substring(8).trim();
      // Collect all remaining lines as part of the message
      for (let j = i + 1; j < lines.length; j++) {
        const nextLine = lines[j].trim();
        if (nextLine.startsWith('SERVICE:') || nextLine.startsWith('PRICE:') || 
            nextLine.startsWith('DESCRIPTION:') || nextLine.startsWith('REASON:') || 
            nextLine.startsWith('SUMMARY:')) {
          break;
        }
        if (nextLine) {
          message += '\n' + nextLine;
        }
      }
    } else if (line.startsWith('SERVICE:')) {
      service = line.substring(8).trim();
    } else if (line.startsWith('PRICE:')) {
      price = line.substring(6).trim();
    } else if (line.startsWith('DESCRIPTION:')) {
      description = line.substring(12).trim();
    } else if (line.startsWith('REASON:')) {
      reason = line.substring(7).trim();
    } else if (line.startsWith('SUMMARY:')) {
      summary = line.substring(8).trim();
    }
  }

  const result: AgentDecision = {
    action,
    thought,
    message: message || response, // Fallback to full response if parsing fails
  };

  if (action === 'CLOSE_DEAL' && service && price) {
    result.closeDetails = { service, price, description };
  }

  if (action === 'TRANSFER_TO_HUMAN') {
    result.transferDetails = { reason, summary };
  }

  return result;
}

